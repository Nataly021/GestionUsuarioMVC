    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
   if (txtnombre.getText().trim().isEmpty() || 
            txtapellido.getText().trim().isEmpty() || 
            txtcargo.getText().trim().isEmpty() || 
            txtsalario.getText().trim().isEmpty() || 
            txtdepa.getText().trim().isEmpty()) {
            
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Por favor complete todos los campos.", 
                "Advertencia", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            // Capturar los datos de las txt
            String nombre = txtnombre.getText().trim();
            String apellido = txtapellido.getText().trim();
            String cargo = txtcargo.getText().trim();
            double salarioBase = Double.parseDouble(txtsalario.getText().trim());
            String departamento = txtdepa.getText().trim();
            
            Empleado nuevoEmpleado = new Empleado();
            nuevoEmpleado.setNombre(nombre);
            nuevoEmpleado.setApellido(apellido);
            nuevoEmpleado.setCargo(cargo);
            nuevoEmpleado.setSalarioBase(salarioBase);
            nuevoEmpleado.setDepartamento(departamento);
            
            // Instanciar el dao y llamar al metodo para guardar
            EmpleadoDAO dao = new EmpleadoDAO();
          
           boolean guardadoExitoso = dao.insertar(nuevoEmpleado);
            
            if (guardadoExitoso) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Empleado guardado exitosamente", 
                    "exito", 
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
              
                
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "No se pudo guardar el empleado.", 
                    "Error", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            }
            
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "El salario base debe ser un valor numerico valido.", 
                "Error de formato", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
            txtsalario.requestFocus();
            
       } catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        e.getClass().getName() + "\n" + e.getMessage(),
        "Error al guardar",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}
    }//GEN-LAST:event_jButton3ActionPerformed

