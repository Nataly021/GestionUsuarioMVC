  private void cargarEmpleadosActivos() {
    try {
        EmpleadoDAO dao = new EmpleadoDAO();
        ArrayList<Empleado> lista = dao.listaarchivos();
                                                                                 
        System.out.println("Lista recibida por el formulario: " + lista.size());

        jsbSeleccionEmpleado.removeAllItems();

        for (Empleado emp : lista) {
            jsbSeleccionEmpleado.addItem(emp);
        }

        if (!lista.isEmpty()) {
            jsbSeleccionEmpleado.setSelectedIndex(0);
            mostrarDatosEnCampos(lista.get(0));
        } else {
            mostrarDatosEnCampos(null);
            JOptionPane.showMessageDialog(this,
                "No hay empleados para mostrar. Revise Output en NetBeans.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Error al cargar empleados: " + e.getMessage());
        e.printStackTrace();
    }
}


        private void mostrarDatosEnCampos(Empleado emp) {
    if (emp != null) {
        txtn.setText(emp.getNombre());
        txta.setText(emp.getApellido());
        txts.setText(String.valueOf(emp.getSalarioBase()));
        txtc.setText(emp.getCargo());
        txtd.setText(emp.getDepartamento());
    } else {
        txtn.setText("");
        txta.setText("");
        txts.setText("");
        txtc.setText("");
        txtd.setText("");
    }
}
   
